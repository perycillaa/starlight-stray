export function measurePixelText(text: string, scale = 1, letterSpacing = 1): number {
  const upper = text.toUpperCase()
  if (!upper.length) return 0
  let total = 0
  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i]!
    const w = ch === ' ' ? 4 : 7
    total += w * scale
    if (i < upper.length - 1) total += letterSpacing * scale
  }
  return total
}

/**
 * Draws razor-sharp 7x9 bitmap pixel typography with hard 1px drop shadow (#1a0f1d).
 * Every single pixel is snapped via Math.round() — guaranteed zero blur!
 */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  options?: {
    align?: 'left' | 'center' | 'right'
    scale?: number
    letterSpacing?: number
    shadowColor?: string
  }
): void {
  const scale = options?.scale ?? 1
  const letterSpacing = options?.letterSpacing ?? 1
  const align = options?.align ?? 'left'
  const shadowColor = options?.shadowColor ?? '#1a0f1d'
  const upper = text.toUpperCase()

  const totalW = measurePixelText(upper, scale, letterSpacing)
  let cursorX =
    align === 'center'
      ? Math.round(x - totalW / 2)
      : align === 'right'
        ? Math.round(x - totalW)
        : Math.round(x)
  const baseY = Math.round(y)

  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i]!
    if (ch === ' ') {
      cursorX += (4 + letterSpacing) * scale
      continue
    }
    const glyph = GLYPHS_7X9[ch] ?? GLYPHS_7X9[' ']!
    // 1. Hard 1px pixel shadow directly below & right
    if (shadowColor) {
      ctx.fillStyle = shadowColor
      for (let gy = 0; gy < glyph.length; gy++) {
        const row = glyph[gy]!
        for (let gx = 0; gx < row.length; gx++) {
          if (row[gx] === '#') {
            ctx.fillRect(cursorX + gx * scale + scale, baseY + gy * scale + scale, scale, scale)
          }
        }
      }
    }
    // 2. Crisp foreground glyph pixels
    ctx.fillStyle = color
    for (let gy = 0; gy < glyph.length; gy++) {
      const row = glyph[gy]!
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] === '#') {
          ctx.fillRect(cursorX + gx * scale, baseY + gy * scale, scale, scale)
        }
      }
    }
    cursorX += (7 + letterSpacing) * scale
  }
}
